`timescale 1ns/1ps

// ============================================================
// Module : replay_buffer
// Layer  : Link layer (Engineer B)
//
// Rewritten against the AXI4-PCIe6 bridge review (L3, L4, L5).
//
// Holds payload Flits (59-DW TLP area each) until the far end ACKs them,
// as PCIe 6.0 Flit mode does: sequence numbers and replay are per Flit.
//
//   * The sequence number is a side output (m_seq), not written over the
//     top 12 bits of the data (L4). link_layer_tx puts it in the DLP.
//   * Everything the framer needs is stored in the buffer. Nothing (tuser,
//     tlast) bypasses it on a separate wire, so a replay sends exactly
//     what was sent first time (L5).
//   * ACK n frees every Flit up to and including n.
//     NAK n frees up to n and replays from n+1.
//     If nothing is ACKed for REPLAY_TIMEOUT cycles while Flits are
//     outstanding, everything unacknowledged is replayed (lost-ACK cover).
//   * ACKs are generated by the far end's data_link_layer_top and arrive
//     in the DLP of its Flits (L3; previously nothing generated ACKs, so
//     the buffer filled after 31 entries and stalled forever).
//
// Pointers are full SEQ_W-bit sequence numbers; the RAM is indexed by
// the low log2(DEPTH) bits. DEPTH must be a power of two <= 2^(SEQ_W-1).
// ============================================================

module replay_buffer #(
    parameter PAYLOAD_W      = 1888,
    parameter SEQ_WIDTH      = 12,
    parameter BUF_DEPTH      = 32,
    parameter REPLAY_TIMEOUT = 16384
)(
    input  wire                   clk,
    input  wire                   rst_n,

    // New payload Flits from flit_payload_builder
    input  wire                   s_valid,
    input  wire [PAYLOAD_W-1:0]   s_data,
    output wire                   s_ready,

    // To link_layer_tx
    output wire                   m_valid,
    output wire [PAYLOAD_W-1:0]   m_data,
    output wire [SEQ_WIDTH-1:0]   m_seq,
    input  wire                   m_ready,

    // ACK/NAK received from the far end (via link_layer_rx DLP)
    input  wire                   rx_ack_valid,
    input  wire [SEQ_WIDTH-1:0]   rx_ack_seq,
    input  wire                   rx_nak_valid,
    input  wire [SEQ_WIDTH-1:0]   rx_nak_seq,

    // Status
    output wire [SEQ_WIDTH-1:0]   outstanding,   // Flits stored, not yet ACKed
    output reg                    replay_event   // pulse on NAK or timeout replay
);

    localparam ADDR_W = $clog2(BUF_DEPTH);
    localparam TMR_W  = $clog2(REPLAY_TIMEOUT + 1);

    reg [PAYLOAD_W-1:0]  mem [0:BUF_DEPTH-1];

    reg [SEQ_WIDTH-1:0]  head_seq;   // next sequence number to assign
    reg [SEQ_WIDTH-1:0]  tail_seq;   // oldest un-ACKed Flit
    reg [SEQ_WIDTH-1:0]  tx_seq;     // next Flit to transmit
    reg [TMR_W-1:0]      timer;

    // OPT-5: mem[] write lives in its own clocked-only block below (no
    // reset in the sensitivity list) so Vivado infers block RAM for the
    // 1888x32 = 60,416-bit array instead of 60,416 flip-flops. head_seq
    // (the pointer) stays in the async-reset control block -- only the
    // array write itself needed to move.
    assign outstanding = head_seq - tail_seq;

    assign s_ready = (outstanding < BUF_DEPTH);
    assign m_valid = (tx_seq != head_seq);
    assign m_data  = mem[tx_seq[ADDR_W-1:0]];
    assign m_seq   = tx_seq;

    // "a acknowledges entries tail..a" is legal if a is inside the window
    wire [SEQ_WIDTH-1:0] ack_next  = rx_ack_seq + 1'b1;
    wire [SEQ_WIDTH-1:0] nak_next  = rx_nak_seq + 1'b1;
    wire ack_in_win = ((ack_next - tail_seq) <= outstanding) && (ack_next != tail_seq);
    wire nak_in_win = ((nak_next - tail_seq) <= outstanding);

    reg [SEQ_WIDTH-1:0] tail_n, tx_n;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            head_seq     <= {SEQ_WIDTH{1'b0}};
            tail_seq     <= {SEQ_WIDTH{1'b0}};
            tx_seq       <= {SEQ_WIDTH{1'b0}};
            timer        <= {TMR_W{1'b0}};
            replay_event <= 1'b0;
        end else begin
            replay_event <= 1'b0;

            // ---- store new Flit (pointer only; mem write moved out, see below) ----
            if (s_valid && s_ready) begin
                head_seq <= head_seq + 1'b1;
            end

            // ---- normal transmit advance ----
            tail_n = tail_seq;
            tx_n   = (m_valid && m_ready) ? tx_seq + 1'b1 : tx_seq;

            // ---- ACK: purge up to and including rx_ack_seq ----
            if (rx_ack_valid && ack_in_win) begin
                tail_n = ack_next;
                timer <= {TMR_W{1'b0}};
            end

            // ---- NAK: purge up to rx_nak_seq, replay from rx_nak_seq+1 ----
            if (rx_nak_valid) begin
                if (nak_in_win) tail_n = nak_next;
                tx_n         = tail_n;
                replay_event <= 1'b1;
                timer        <= {TMR_W{1'b0}};
            end else if (outstanding == {SEQ_WIDTH{1'b0}}) begin
                timer <= {TMR_W{1'b0}};
            end else if (!(rx_ack_valid && ack_in_win)) begin
                if (timer == REPLAY_TIMEOUT[TMR_W-1:0]) begin
                    tx_n         = tail_n;
                    replay_event <= 1'b1;
                    timer        <= {TMR_W{1'b0}};
                end else begin
                    timer <= timer + 1'b1;
                end
            end

            // tx must never sit behind the (new) tail
            if ((tx_n - tail_seq) < (tail_n - tail_seq))
                tx_n = tail_n;

            tail_seq <= tail_n;
            tx_seq   <= tx_n;
        end
    end

    // OPT-5: BRAM-inference-friendly write -- clocked only, no reset.
    always @(posedge clk) begin
        if (s_valid && s_ready)
            mem[head_seq[ADDR_W-1:0]] <= s_data;
    end

    // synthesis translate_off
    initial begin
        if ((BUF_DEPTH & (BUF_DEPTH - 1)) != 0)
            $fatal(1, "[replay_buffer] BUF_DEPTH (%0d) must be a power of two", BUF_DEPTH);
        if (BUF_DEPTH > (1 << (SEQ_WIDTH - 1)))
            $fatal(1, "[replay_buffer] BUF_DEPTH (%0d) must be <= 2^(SEQ_WIDTH-1)", BUF_DEPTH);
    end
    // synthesis translate_on

endmodule
